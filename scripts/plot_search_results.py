#!/usr/bin/env python3
"""
Plot VAULTX search benchmark results produced by run_search_benchmark.sh.
- Reads a CSV from ./data (or a custom path)
- Builds heatmaps for avg ms per lookup and total runtime per t/r/keep_open combination
- Saves a colorful, publication-ready PNG to ./graphs by default
Dependencies: pandas, seaborn, matplotlib
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable, List

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot search benchmark CSV generated by run_search_benchmark.sh",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "csv",
        help="CSV path from run_search_benchmark.sh (e.g., ./data/search_benchmark_YYYYmmdd_HHMMSS.csv)",
    )
    parser.add_argument(
        "-o",
        "--output",
        help="Output PNG path; defaults to ./graphs/<csv_basename>.png",
    )
    parser.add_argument(
        "--title",
        help="Optional plot title override",
        default=None,
    )
    parser.add_argument(
        "--units",
        choices=["mss", "sm"],
        default="mss",
        help="Output units: mss = avg in milliseconds, total in seconds; sm = avg in seconds, total in minutes",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Display the plot window after saving",
    )
    return parser.parse_args()


def resolve_output_path(csv_path: Path, override: str | None) -> Path:
    if override:
        return Path(override).expanduser().resolve()
    repo_root = Path(__file__).resolve().parents[1]
    return (repo_root / "graphs" / f"{csv_path.stem}.png").resolve()


def validate_columns(df: pd.DataFrame, required: Iterable[str]) -> None:
    missing = [col for col in required if col not in df.columns]
    if missing:
        raise ValueError(f"CSV is missing required column(s): {', '.join(missing)}")


def make_heatmaps(
    df: pd.DataFrame,
    keep_values: List[str],
    avg_col: str,
    total_col: str,
    avg_label: str,
    total_label: str,
    avg_fmt: str,
    total_fmt: str,
) -> plt.Figure:
    sns.set_theme(style="whitegrid", font_scale=1.0)
    cmap_avg = sns.color_palette("rocket_r", as_cmap=True)
    cmap_total = sns.color_palette("crest", as_cmap=True)

    fig, axes = plt.subplots(
        nrows=3,
        ncols=len(keep_values),
        figsize=(4.5 * len(keep_values) + 1.5, 11.0),
        squeeze=False,
        gridspec_kw={"height_ratios": [1.0, 1.0, 0.4]},
    )

    for idx, keep_flag in enumerate(keep_values):
        subset = df[df["keep_open"] == keep_flag]
        if subset.empty:
            continue

        avg_pivot = subset.pivot_table(
            index="r",
            columns="t",
            values=avg_col,
            aggfunc="mean",
        )
        total_pivot = subset.pivot_table(
            index="r",
            columns="t",
            values=total_col,
            aggfunc="mean",
        )

        ax_avg = axes[0, idx]
        sns.heatmap(
            avg_pivot,
            ax=ax_avg,
            cmap=cmap_avg,
            annot=True,
            fmt=avg_fmt,
            cbar=(idx == len(keep_values) - 1),
        )
        ax_avg.set_title(f"{avg_label} (keep_open={keep_flag})")
        ax_avg.set_xlabel("I/O threads (-t)")
        ax_avg.set_ylabel("Record threads (-r)")

        ax_total = axes[1, idx]
        sns.heatmap(
            total_pivot,
            ax=ax_total,
            cmap=cmap_total,
            annot=True,
            fmt=total_fmt,
            cbar=(idx == len(keep_values) - 1),
        )
        ax_total.set_title(f"{total_label} (keep_open={keep_flag})")
        ax_total.set_xlabel("I/O threads (-t)")
        ax_total.set_ylabel("Record threads (-r)")

    # Leaderboard (top 5 fastest avg lookups) placed in bottom-left cell; others hidden.
    leaderboard_ax = axes[2, 0]
    axes[2, 1:] = [ax.axis("off") for ax in axes[2, 1:]]
    top = df.sort_values(avg_col).head(5)
    lines = [
        f"{i+1}. -t {row.t} -r {row.r} -O {row.keep_open} | avg {row[avg_col]:.2f} {avg_label.split()[0]} | total {row[total_col]:.2f} {total_label.split()[0]}"
        for i, row in top.reset_index(drop=True).iterrows()
    ]
    leaderboard_ax.axis("off")
    leaderboard_ax.text(
        0.01,
        0.95,
        "Top 5 fastest (avg ms/lookup):\n" + "\n".join(lines),
        va="top",
        ha="left",
        fontsize=10,
        family="monospace",
    )

    plt.tight_layout()
    return fig


def main() -> None:
    args = parse_args()
    csv_path = Path(args.csv).expanduser().resolve()
    if not csv_path.exists():
        raise FileNotFoundError(f"CSV not found: {csv_path}")

    df = pd.read_csv(csv_path)
    required = {
        "t",
        "r",
        "keep_open",
        "avg_ms_per_lookup",
        "total_ms",
        "lookups",
        "difficulty",
    }
    validate_columns(df, required)

    # Normalize dtypes and ordering.
    df["t"] = df["t"].astype(int)
    df["r"] = df["r"].astype(int)
    df["avg_ms_per_lookup"] = df["avg_ms_per_lookup"].astype(float)
    df["total_ms"] = df["total_ms"].astype(float)
    if "total_s" not in df.columns:
        df["total_s"] = df["total_ms"] / 1000.0
    df["keep_open"] = df["keep_open"].astype(str)

    keep_values = sorted(df["keep_open"].unique())

    # Unit handling
    if args.units == "mss":
        df["avg_disp"] = df["avg_ms_per_lookup"]
        df["total_disp"] = df["total_s"]
        avg_label = "Avg ms/lookup"
        total_label = "Total time s"
        avg_fmt = ".2f"
        total_fmt = ".2f"
    else:  # sm
        df["avg_disp"] = df["avg_ms_per_lookup"] / 1000.0
        df["total_disp"] = df["total_s"] / 60.0
        avg_label = "Avg s/lookup"
        total_label = "Total time min"
        avg_fmt = ".3f"
        total_fmt = ".3f"

    fig = make_heatmaps(
        df,
        keep_values,
        avg_col="avg_disp",
        total_col="total_disp",
        avg_label=avg_label,
        total_label=total_label,
        avg_fmt=avg_fmt,
        total_fmt=total_fmt,
    )

    title_text = args.title or f"VAULTX search benchmark ({csv_path.name})"
    fig.suptitle(title_text, fontsize=14, fontweight="bold")
    plt.tight_layout(rect=(0, 0, 1, 0.95))

    output_path = resolve_output_path(csv_path, args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=220)

    if args.show:
        plt.show()

    print(f"Saved plot to {output_path}")


if __name__ == "__main__":
    main()
